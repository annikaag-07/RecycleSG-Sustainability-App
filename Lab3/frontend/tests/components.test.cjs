// Offline unit tests. Transpile actual TS modules with existing TypeScript;
// stub only external boundaries. No Expo runtime or live Supabase required.
const { test } = require('node:test');
const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const ts = require('typescript');

function load(relative, stubs = {}) {
  const filename = path.join(__dirname, '../src', relative);
  const source = ts.transpileModule(fs.readFileSync(filename, 'utf8'), {
    compilerOptions: { module: ts.ModuleKind.CommonJS, target: ts.ScriptTarget.ES2022 },
  }).outputText;
  const module = { exports: {} };
  new Function('require', 'module', 'exports', source)((name) => {
    if (Object.hasOwn(stubs, name)) return stubs[name];
    throw new Error(`Unexpected dependency ${name} in ${relative}`);
  }, module, module.exports);
  return module.exports;
}

test('photo suggestion uploads original bytes and handles timeout, cancellation and invalid responses', async () => {
  const oldUrl=process.env.EXPO_PUBLIC_VERIFICATION_URL, oldFetch=global.fetch, oldTimeout=global.setTimeout;
  process.env.EXPO_PUBLIC_VERIFICATION_URL='http://cv.test/';
  const { classifyPhoto }=load('shared/api/classification.ts', {
    'react-native':{Platform:{OS:'web'}}, './errors':load('shared/api/errors.ts'),
  });
  const photo={uri:'data:image/png;base64,YWJj',base64:'YWJj',mimeType:'image/png'};
  try {
    global.fetch=async(url,options)=>{
      assert.equal(url,'http://cv.test/classify');
      assert.equal(options.headers,undefined,'multipart boundary must be generated by fetch');
      const file=options.body.get('file');
      assert.equal(file.type,'image/png');
      assert.equal(await file.text(),'abc');
      return {ok:true,json:async()=>({status:'ok',material:'plastic',confidence:0.9})};
    };
    assert.equal((await classifyPhoto(photo,new AbortController().signal)).material,'plastic');
    global.fetch=async()=>({ok:true,json:async()=>({status:'ok',material:null})});
    await assert.rejects(classifyPhoto(photo,new AbortController().signal),/Choose the material manually/);
    global.fetch=(_url,{signal})=>new Promise((_resolve,reject)=>{
      if(signal.aborted) reject(new Error('aborted'));
      else signal.addEventListener('abort',()=>reject(new Error('aborted')),{once:true});
    });
    const cancelled=new AbortController();
    const request=classifyPhoto(photo,cancelled.signal);
    cancelled.abort();
    await assert.rejects(request,/Choose the material manually/);
    global.setTimeout=(callback,delay)=>{assert.equal(delay,20000);return oldTimeout(callback,1);};
    await assert.rejects(classifyPhoto(photo,new AbortController().signal),/Choose the material manually/);
  } finally {
    global.fetch=oldFetch;global.setTimeout=oldTimeout;
    if(oldUrl===undefined) delete process.env.EXPO_PUBLIC_VERIFICATION_URL;
    else process.env.EXPO_PUBLIC_VERIFICATION_URL=oldUrl;
  }
});

